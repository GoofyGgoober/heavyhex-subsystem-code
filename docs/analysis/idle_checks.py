"""Saved Kingston idle-fit residuals and a conditional estimator check; no circuit sampling.

Requires build/followup/fixed-joint.json, generated by the command in followup/README.md.
Binomial resampling below plants the fitted contrast at the observed phases (X/Y) or
observed population midpoints (Z). It checks transformation/selection in this regime,
not nonstationary noise, input correctness, randomization variance or physical coverage.

    PYTHONPATH=. OPENBLAS_NUM_THREADS=1 python docs/analysis/idle_checks.py
"""

from __future__ import annotations

import numpy as np
from scipy.stats import chi2

from followup import analysis as a

from common import REPO, read, write_json


def contrasts(row, basis):
    keys = ("x", "y", "shots_x", "shots_y") if basis == "XY" else ("p0", "p1", "shots_0", "shots_1")
    values = [np.asarray(row[k], float) for k in keys]
    return (a.r_of if basis == "XY" else a.c_of)(*values)


def joint_residuals(xy, z, fitted):
    rates = np.array([fitted["rate_t1"][0], fitted["rate_t_q"][0]])
    views = {}
    for basis, row in (("XY", xy), ("Z", z)):
        value, variance = contrasts(row, basis)
        keep = value > a.MIN_R
        te, tz, g = (np.asarray(row[k])[keep] for k in ("equator_us", "along_z_us", "pulses"))
        offset_points = np.log(value[keep] / g) + tz * rates[0] + te * rates[1]
        offset = np.average(offset_points, weights=1 / variance[keep])
        residual = (offset_points - offset) / np.sqrt(variance[keep])
        views[basis] = {"used": int(keep.sum()), "standardized_residual": residual.tolist()}
    dof = sum(v["used"] for v in views.values()) - 4
    statistic = sum(np.square(v["standardized_residual"]).sum() for v in views.values())
    return {
        "views": views,
        "chi2": float(statistic),
        "nominal_dof": dof,
        "chi2_red": float(statistic / dof),
        "nominal_p": float(chi2.sf(statistic, dof)),
    }


def rate_batch(t, value, variance, g):
    """Vectorized form of the archived weighted log slope and unscaled covariance."""
    keep = value > a.MIN_R
    w = np.where(keep, 1 / np.maximum(variance, 1e-15), 0)
    y = np.log(np.maximum(value, a.MIN_R) / g)
    sw, sx = w.sum(-1), (w * t).sum(-1)
    sxx, sy, sxy = (w * t**2).sum(-1), (w * y).sum(-1), (w * t * y).sum(-1)
    determinant = sw * sxx - sx**2
    rate = -(sw * sxy - sx * sy) / determinant
    se = np.sqrt(sw / determinant)
    return rate, se, keep.sum(-1)


def planted_check(row, basis, rng, repetitions=2000):
    value, var = contrasts(row, basis)
    g = np.asarray(row["pulses"], float)
    if basis == "XY":
        t = np.asarray(row["equator_us"], float)
        g = g * np.exp(-np.asarray(row["along_z_us"]) / row["t1_us"])
    else:
        t = np.array([1, 2, 4, 8, 16], float)
    fitted = a.log_decay(t, value, var, g)
    truth = fitted["offset"] * g * np.exp(-fitted["rate"][0] * t)
    if np.any((truth <= 0) | (truth >= 1)):
        raise ValueError("Planted contrasts must be physical without clipping")
    if basis == "XY":
        phase = np.arctan2(row["y"], row["x"])
        n0, n1 = (np.asarray(row[k], int) for k in ("shots_x", "shots_y"))
        x = (
            1
            - 2 * rng.binomial(n0, (1 - truth * np.cos(phase)) / 2, size=(repetitions, len(t))) / n0
        )
        y = (
            1
            - 2 * rng.binomial(n1, (1 - truth * np.sin(phase)) / 2, size=(repetitions, len(t))) / n1
        )
        simulated, variance = a.r_of(x, y, n0, n1)
        midpoint_adjustments = 0
    else:
        midpoint = (np.asarray(row["p0"]) + row["p1"]) / 2
        held = np.clip(midpoint, truth / 2, 1 - truth / 2)
        midpoint_adjustments = int(np.count_nonzero(midpoint != held))
        n0, n1 = (np.asarray(row[k], int) for k in ("shots_0", "shots_1"))
        p0 = rng.binomial(n0, held - truth / 2, size=(repetitions, len(t))) / n0
        p1 = rng.binomial(n1, held + truth / 2, size=(repetitions, len(t))) / n1
        simulated, variance = a.c_of(p0, p1, n0, n1)
    rate, se, kept = rate_batch(t, simulated, variance, g)
    valid = (kept >= 3) & np.isfinite(rate) & np.isfinite(se)
    pull = (rate[valid] - fitted["rate"][0]) / se[valid]
    return {
        "observed_points_retained": fitted["used"],
        "observed_contrast_range": [float(value.min()), float(value.max())],
        "planted_rate": fitted["rate"][0],
        "planted_contrast": truth.tolist(),
        "midpoint_adjustments": midpoint_adjustments,
        "repetitions": repetitions,
        "valid": int(valid.sum()),
        "point_discard_fraction": float((kept < len(t)).mean()),
        "mean_pull": float(pull.mean()),
        "sd_pull": float(pull.std(ddof=1)),
        "nominal95_coverage": float(np.mean(np.abs(pull) <= 1.96)),
    }


def main():
    source = read(REPO / "build/followup/fixed-joint.json")
    inputs = source["inputs"]
    xy, z = ({r["qubit"]: r for r in inputs[k]["qubits"]} for k in ("xy", "z"))
    joint = {r["qubit"]: r for r in inputs["joint"]["qubits"]}
    rng = np.random.default_rng(1313)
    residuals, planted = {}, {"XY": {}, "Z": {}}
    for q in sorted(joint):
        residuals[str(q)] = joint_residuals(xy[q], z[q], joint[q])
        for basis, rows in (("XY", xy), ("Z", z)):
            planted[basis][str(q)] = planted_check(rows[q], basis, rng)
    reduced = np.array([r["chi2_red"] for r in residuals.values()])
    summary = {
        "joint_chi2_red_range": [float(reduced.min()), float(reduced.max())],
        "joint_chi2_red_median": float(np.median(reduced)),
        "joint_nominal_p_below_005": sum(r["nominal_p"] < 0.05 for r in residuals.values()),
        "joint_chi2": sum(r["chi2"] for r in residuals.values()),
        "joint_nominal_dof": sum(r["nominal_dof"] for r in residuals.values()),
    }
    for basis, rows in planted.items():
        summary[basis] = {
            "used_range": [
                min(r["observed_points_retained"] for r in rows.values()),
                max(r["observed_points_retained"] for r in rows.values()),
            ],
            "minimum_observed_contrast": min(
                r["observed_contrast_range"][0] for r in rows.values()
            ),
            "mean_pull_range": [
                min(r["mean_pull"] for r in rows.values()),
                max(r["mean_pull"] for r in rows.values()),
            ],
            "coverage_range": [
                min(r["nominal95_coverage"] for r in rows.values()),
                max(r["nominal95_coverage"] for r in rows.values()),
            ],
            "any_point_discard_fraction": max(r["point_discard_fraction"] for r in rows.values()),
            "midpoint_adjustments": sum(r["midpoint_adjustments"] for r in rows.values()),
        }
    out = {
        "what": __doc__,
        "seed": 1313,
        "source_sha256": source["input_sha256"],
        "joint_residuals": residuals,
        "planted_checks": planted,
        "summary": summary,
        "caveat": "Nominal log-fit residual references, not calibrated physical-model tests. "
        "Planted binomial checks condition on fitted contrasts, nuisance inputs and independence; "
        "do not cover drift, shared/randomization noise, pulse-model error or Fez cutoff behavior.",
    }
    write_json("idle_checks.json", out)
    print(summary)


if __name__ == "__main__":
    main()
